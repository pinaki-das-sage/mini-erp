<?php
declare(strict_types=1);

return [
    "CREATE TABLE ME_USERS (
        ID VARCHAR2(40) PRIMARY KEY, USERNAME VARCHAR2(100) NOT NULL UNIQUE,
        PASSWORD_HASH VARCHAR2(255) NOT NULL, ACTIVE NUMBER(1) DEFAULT 1 NOT NULL,
        CHECK (ACTIVE IN (0, 1))
    )",
    "CREATE TABLE ME_ROLES (CODE VARCHAR2(50) PRIMARY KEY)",
    "CREATE TABLE ME_USER_ROLES (
        USER_ID VARCHAR2(40) NOT NULL REFERENCES ME_USERS(ID),
        ROLE_CODE VARCHAR2(50) NOT NULL REFERENCES ME_ROLES(CODE),
        PRIMARY KEY (USER_ID, ROLE_CODE)
    )",
    "CREATE TABLE ME_NOTES (
        ID VARCHAR2(40) PRIMARY KEY, BODY VARCHAR2(2000 BYTE) NOT NULL,
        VERSION NUMBER(10) DEFAULT 1 NOT NULL, CHECK (VERSION > 0)
    )",
    "CREATE TABLE ME_ACTIONS (
        ACTION_REFERENCE VARCHAR2(100) PRIMARY KEY,
        ACTOR_ID VARCHAR2(40) NOT NULL REFERENCES ME_USERS(ID),
        PAYLOAD_HASH VARCHAR2(64) NOT NULL, RESULT_JSON CLOB,
        CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
    )",
    "CREATE TABLE ME_AUDIT (
        ID VARCHAR2(32) PRIMARY KEY,
        ACTION_REFERENCE VARCHAR2(100) NOT NULL REFERENCES ME_ACTIONS(ACTION_REFERENCE),
        ACTOR_ID VARCHAR2(40) NOT NULL REFERENCES ME_USERS(ID),
        EVENT_TYPE VARCHAR2(50) NOT NULL, DETAILS_JSON CLOB NOT NULL,
        CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
    )",
];

<?php
declare(strict_types=1);

// One balance row per product (company-scoped). The product service creates this row, with
// ON_HAND = 0 and RESERVED = 0, in the same transaction that creates the product.
return [
    <<<'SQL'
    CREATE TABLE ME_INV_STOCK_BALANCE (
        COMPANY_ID NUMBER(10) NOT NULL,
        PRODUCT_ID NUMBER(10) NOT NULL,
        ON_HAND NUMBER(10) DEFAULT 0 NOT NULL,
        RESERVED NUMBER(10) DEFAULT 0 NOT NULL,
        AVAILABLE NUMBER(10) GENERATED ALWAYS AS (ON_HAND - RESERVED) VIRTUAL,
        WHEN_UPDATED TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
        CONSTRAINT ME_INV_BAL_PK PRIMARY KEY (COMPANY_ID, PRODUCT_ID),
        CONSTRAINT ME_INV_BAL_PROD_FK FOREIGN KEY (COMPANY_ID, PRODUCT_ID)
            REFERENCES ME_INV_PRODUCTS (COMPANY_ID, PRODUCT_ID),
        CONSTRAINT ME_INV_BAL_QTY_CK CHECK (ON_HAND >= 0 AND RESERVED >= 0 AND RESERVED <= ON_HAND)
    )
    SQL,
    <<<'SQL'
    CREATE OR REPLACE TRIGGER ME_INV_STOCK_BAL_BU_TRG
    BEFORE UPDATE ON ME_INV_STOCK_BALANCE
    FOR EACH ROW
    BEGIN
        :NEW.WHEN_UPDATED := SYSTIMESTAMP;
    END;
    SQL,
];

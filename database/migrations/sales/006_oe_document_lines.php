<?php
declare(strict_types=1);

// Quantity is a positive whole number in the new database document.
// Inventory/Logistics references are validated through agreed provider interfaces;
// cross-module foreign keys belong in a separately reviewed integration migration.
// Services enforce source-line ownership, Order-only Trip fields, complete line sets,
// exact monetary capacity, and parent VERSION/WHENMODIFIED updates in one transaction.
return [
    'CREATE TABLE ME_OE_DOCUMENT_LINES (
        RECORD# NUMBER(15) GENERATED BY DEFAULT AS IDENTITY,
        CNY# NUMBER(10) NOT NULL,
        DOCUMENT_RECORD# NUMBER(15) NOT NULL,
        LINE_NUMBER NUMBER(10) NOT NULL,
        ITEM_CODE VARCHAR2(30 CHAR) NOT NULL,
        DESCRIPTION VARCHAR2(200 CHAR),
        QUANTITY NUMBER NOT NULL,
        UNIT_PRICE NUMBER(12,2) NOT NULL,
        SOURCE_LINE_RECORD# NUMBER(15),
        TRIP_ID NUMBER,
        LOGISTICS_TRIP_LINE_ID NUMBER,
        TRIP_STATUS VARCHAR2(12 CHAR),
        WHENCREATED TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
        WHENMODIFIED TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
        CONSTRAINT ME_OE_LINE_PK PRIMARY KEY (CNY#, RECORD#),
        CONSTRAINT ME_OE_LINE_COMPANY_FK FOREIGN KEY (CNY#) REFERENCES ME_COMPANY (ID),
        CONSTRAINT ME_OE_LINE_DOCUMENT_FK FOREIGN KEY (CNY#, DOCUMENT_RECORD#)
            REFERENCES ME_OE_DOCUMENTS (CNY#, RECORD#),
        CONSTRAINT ME_OE_LINE_SOURCE_FK FOREIGN KEY (CNY#, SOURCE_LINE_RECORD#)
            REFERENCES ME_OE_DOCUMENT_LINES (CNY#, RECORD#),
        CONSTRAINT ME_OE_LINE_POSITION_UK UNIQUE (CNY#, DOCUMENT_RECORD#, LINE_NUMBER),
        CONSTRAINT ME_OE_LINE_QTY_CK CHECK (QUANTITY > 0 AND QUANTITY = TRUNC(QUANTITY)),
        CONSTRAINT ME_OE_LINE_PRICE_CK CHECK (UNIT_PRICE >= 0),
        CONSTRAINT ME_OE_LINE_NUMBER_CK CHECK (LINE_NUMBER > 0)
    )',
    'CREATE INDEX ME_OE_LINE_SOURCE_IX ON ME_OE_DOCUMENT_LINES (CNY#, SOURCE_LINE_RECORD#)',
];

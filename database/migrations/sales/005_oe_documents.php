<?php
declare(strict_types=1);

// New document model: Quote -> Order -> Invoice. Logistics owns Trips and delivery.
// Services generate business numbers, map public statuses, validate type-specific fields,
// and maintain VERSION/WHENMODIFIED. DDL alone does not implement lifecycle actions.
return [
    "CREATE TABLE ME_OE_DOCUMENTS (
        RECORD# NUMBER(15) GENERATED BY DEFAULT AS IDENTITY,
        CNY# NUMBER(10) NOT NULL,
        DOCUMENT_TYPE VARCHAR2(20 CHAR) NOT NULL,
        DOCUMENT_NUMBER VARCHAR2(20 CHAR) NOT NULL,
        CUSTOMER_RECORD# NUMBER(15) NOT NULL,
        WAREHOUSE_ID VARCHAR2(20 CHAR) NOT NULL,
        DOCUMENT_DATE DATE NOT NULL,
        STATUS VARCHAR2(20 CHAR) DEFAULT 'DRAFT' NOT NULL,
        VALID_UNTIL DATE,
        REQUESTED_DELIVERY_DATE DATE,
        CUSTOMER_PO_NUMBER VARCHAR2(30 CHAR),
        SHIPPING_ADDRESS VARCHAR2(500 CHAR),
        PAYMENT_TERMS VARCHAR2(20 CHAR) NOT NULL,
        DUE_DATE DATE,
        NOTES VARCHAR2(500 CHAR),
        VERSION NUMBER(10) DEFAULT 1 NOT NULL,
        WHENCREATED TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
        WHENMODIFIED TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
        CONSTRAINT ME_OE_DOC_PK PRIMARY KEY (CNY#, RECORD#),
        CONSTRAINT ME_OE_DOC_COMPANY_FK FOREIGN KEY (CNY#) REFERENCES ME_COMPANY (ID),
        CONSTRAINT ME_OE_DOC_CUSTOMER_FK FOREIGN KEY (CNY#, CUSTOMER_RECORD#)
            REFERENCES ME_OE_CUSTOMERS (CNY#, RECORD#),
        CONSTRAINT ME_OE_DOC_NUMBER_UK UNIQUE (CNY#, DOCUMENT_TYPE, DOCUMENT_NUMBER),
        CONSTRAINT ME_OE_DOC_TYPE_CK CHECK (
            DOCUMENT_TYPE IN ('SALES_QUOTE', 'SALES_ORDER', 'SALES_INVOICE')
        ),
        CONSTRAINT ME_OE_DOC_STATUS_CK CHECK (
            (DOCUMENT_TYPE IN ('SALES_QUOTE', 'SALES_INVOICE') AND STATUS IN ('DRAFT', 'SUBMITTED'))
            OR
            (DOCUMENT_TYPE = 'SALES_ORDER' AND STATUS IN ('DRAFT', 'SUBMITTED', 'IN_PROGRESS', 'CLOSED'))
        )
    )",
    'CREATE INDEX ME_OE_DOC_CUSTOMER_IX ON ME_OE_DOCUMENTS (CNY#, CUSTOMER_RECORD#)',
];

<?php
declare(strict_types=1);

// Requires the shared foundation, company/permission and multi-tenancy migrations.
// ID is generated for numeric Customer URLs. CUSTOMER_CODE is the immutable business identifier.
// Customer services validate code format/immutability, trimmed required text, email and phone.
// Customer Code uniqueness preserves entered case within the company.
// Outstanding balance is derived from Submitted Invoices and payments, never stored here.
return [
    "CREATE TABLE ME_OE_CUSTOMERS (
        ID NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
        COMPANY_ID NUMBER(10) NOT NULL,
        CUSTOMER_CODE VARCHAR2(20 CHAR) NOT NULL,
        CUSTOMER_NAME VARCHAR2(100 CHAR) NOT NULL,
        IS_ACTIVE VARCHAR2(1 CHAR) DEFAULT 'T' NOT NULL,
        CONTACT_NAME VARCHAR2(100 CHAR),
        EMAIL_ADDRESS VARCHAR2(254 CHAR),
        PHONE_NUMBER VARCHAR2(25 CHAR),
        BILLING_ADDRESS_LINE_1 VARCHAR2(150 CHAR) NOT NULL,
        BILLING_ADDRESS_LINE_2 VARCHAR2(150 CHAR),
        CITY VARCHAR2(80 CHAR) NOT NULL,
        STATE_PROVINCE VARCHAR2(80 CHAR),
        POSTAL_CODE VARCHAR2(20 CHAR),
        COUNTRY VARCHAR2(80 CHAR) NOT NULL,
        PAYMENT_TERMS VARCHAR2(20 CHAR) DEFAULT 'NET_30' NOT NULL,
        NOTES VARCHAR2(500 CHAR),
        CONSTRAINT ME_OE_CUST_PK PRIMARY KEY (ID),
        CONSTRAINT ME_OE_CUST_COMPANY_FK FOREIGN KEY (COMPANY_ID) REFERENCES ME_COMPANY(ID),
        CONSTRAINT ME_OE_CUST_CODE_UK UNIQUE (COMPANY_ID, CUSTOMER_CODE),
        CONSTRAINT ME_OE_CUST_ACTIVE_CK CHECK (IS_ACTIVE IN ('T', 'F')),
        CONSTRAINT ME_OE_CUSTOMERS_TERMS_CK CHECK (PAYMENT_TERMS IN ('DUE_ON_RECEIPT', 'NET_15', 'NET_30'))
    )",
];

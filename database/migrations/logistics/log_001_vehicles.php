<?php
declare(strict_types=1);

return [
    "CREATE TABLE ME_LOG_VEHICLES (
    COMPANY_ID          NUMBER(22) NOT NULL,
    ID                  NUMBER GENERATED BY DEFAULT AS IDENTITY,
    VEHICLE_CODE        NUMBER NOT NULL,
    REGISTRATION_NUMBER VARCHAR2(40) NOT NULL,
    DESCRIPTION         VARCHAR2(255),
    CAPACITY            NUMBER(12,3) NOT NULL,
    /* Oracle does not favor Boolean */
    ISACTIVE            CHAR(1) DEFAULT 'T' NOT NULL,

    CREATED_AT          TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT          TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP,
    CREATED_BY          NUMBER(30), /*Foreign Key - USER ID Field*/
    UPDATED_BY          NUMBER(30),  

    /* Primary key */
    CONSTRAINT PK_ME_LOG_VEHICLES
        PRIMARY KEY (COMPANY_ID, ID),
  
    /*  Unique key  */
    CONSTRAINT UK_LOG_VEH_CODE
        UNIQUE (COMPANY_ID, VEHICLE_CODE),
  
    /* Foreign Key */
    CONSTRAINT FK_LOG_VEH_COMPANY
        FOREIGN KEY (COMPANY_ID)
    REFERENCES ME_COMPANY (ID),
    
    /* Check Constraints */
    CONSTRAINT CK_LOG_VEH_ACTIVE
        CHECK (ISACTIVE IN ('T', 'F')),
    CONSTRAINT CK_LOG_VEH_CAPACITY
        CHECK (CAPACITY > 0)
)",

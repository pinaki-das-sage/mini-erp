<?php
declare(strict_types=1);

return [
    "CREATE TABLE ME_LOG_DRIVERS (
    COMPANY_ID          NUMBER(22) NOT NULL,
    ID                  NUMBER GENERATED BY DEFAULT AS IDENTITY,
    DRIVER_CODE         VARCHAR2(30) NOT NULL,
    USER_ID             NUMBER(30), /* added 40 as limit since 
                                                  ID in ME_USERS is VARCHAR2(40)*/
    FIRST_NAME          VARCHAR2(100) NOT NULL,
    LAST_NAME           VARCHAR2(100) NOT NULL,
    PHONE               VARCHAR2(30),
    LICENCE_NUMBER      VARCHAR2(50) NOT NULL,
    LICENCE_EXPIRY      DATE NOT NULL,
    /* Oracle does not favor Boolean */
    ISACTIVE            CHAR(1) DEFAULT 'T' NOT NULL,
  
    CREATED_AT          TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT          TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP,
    CREATED_BY          NUMBER(30), /*Foreign Key - User ID Field*/
    UPDATED_BY          NUMBER(30),   

    /* Primary Key */
    CONSTRAINT PK_ME_LOG_DRIVERS
        PRIMARY KEY (COMPANY_ID, ID),

    /* Unique Key */
    CONSTRAINT UK_LOG_DRV_CODE
        UNIQUE (COMPANY_ID, DRIVER_CODE),

    /* Foreign Key */
    CONSTRAINT FK_LOG_DRV_COMPANY
        FOREIGN KEY (COMPANY_ID)
    REFERENCES ME_COMPANY (ID),

    /* Check Constraints */
    CONSTRAINT CK_LOG_DRV_ACTIVE
        CHECK (ISACTIVE IN ('T', 'F'))
)",
];

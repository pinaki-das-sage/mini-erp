const fs=require('fs'),assert=require('assert/strict'),path=require('path'),crypto=require('crypto');
const file='docs/sales-and-order-entry-db-design.md',text=fs.readFileSync(file,'utf8');
const split=s=>s.split(',').map(x=>x.trim());
const tables=new Map();let explicitIndexes=0;
for(const [,name,body]of text.matchAll(/CREATE TABLE (ME_OE_\w+) \(\n([\s\S]*?)\n\);/g)){
 const cols=new Map([...body.matchAll(/^    ([A-Z][A-Z0-9_#]*)\s+(NUMBER\([^)]*\)|VARCHAR2\([^)]*\)|CHAR\([^)]*\)|DATE)/gm)].map(m=>[m[1],m[2]]));
 const pk=split(/PRIMARY KEY \(([^)]+)\)/.exec(body)[1]);assert.deepEqual(pk,['CNY#','RECORD#'],name);
 const unique=[...body.matchAll(/UNIQUE \(([^)]+)\)/g)].map(m=>split(m[1]));
 const foreign=[...body.matchAll(/FOREIGN KEY \(([^)]+)\)\s*REFERENCES ([A-Z_]+) \(([^)]+)\)/g)].map(m=>({cols:split(m[1]),parent:m[2],target:split(m[3])}));
 for(const c of ['RECORD#','CNY#'])assert(cols.has(c),name+'.'+c);
 for(const c of cols.keys())assert(!['ID','COMPANY_ID'].includes(c),name+'.'+c);
 assert(/RECORD#\s+NUMBER\(15\) GENERATED BY DEFAULT AS IDENTITY/.test(body));
 tables.set(name,{cols,pk,unique,foreign,indexes:[pk,...unique]});
}
assert.equal(tables.size,5);
for(const [,name,table,cols]of text.matchAll(/CREATE INDEX (\w+)\s+ON (ME_OE_\w+) \(([^)]+)\)/g)){
 assert(tables.has(table));tables.get(table).indexes.push(split(cols));explicitIndexes++;
}
assert.equal(explicitIndexes,3);
const external=new Map([
 ['ME_COMPANY',{cols:new Map([['ID','NUMBER(10)']]),pk:['ID'],unique:[]}],
 ['ME_ACTIONS',{cols:new Map([['COMPANY_ID','NUMBER(10)'],['ACTION_REFERENCE','VARCHAR2(100)']]),pk:['COMPANY_ID','ACTION_REFERENCE'],unique:[]}]
]);
let foreignKeys=0;
for(const [name,t]of tables){
 for(const key of [t.pk,...t.unique,...t.indexes])for(const col of key)assert(t.cols.has(col),name+' missing '+col);
 for(const f of t.foreign){
  const p=tables.get(f.parent)||external.get(f.parent);assert(p,'Unknown parent '+f.parent);
  assert([p.pk,...p.unique].some(k=>JSON.stringify(k)===JSON.stringify(f.target)),'Not a parent key');
  assert.equal(f.cols.length,f.target.length);assert.equal(f.cols[0],'CNY#');
  for(let i=0;i<f.cols.length;i++)assert.equal(t.cols.get(f.cols[i]),p.cols.get(f.target[i]),name+' type mismatch');
  assert(t.indexes.some(k=>JSON.stringify(k.slice(0,f.cols.length))===JSON.stringify(f.cols)),name+' FK lacks index '+f.cols);
  foreignKeys++;
 }
}
assert.equal(foreignKeys,12);
assert.equal(tables.get('ME_OE_CUSTOMERS').cols.get('IS_ACTIVE'),'CHAR(1)');
assert.equal(tables.get('ME_OE_CUSTOMERS').cols.get('AMOUNT_CUSTOMER_OWES_US'),'NUMBER(18,2)');
assert(/AMOUNT_CUSTOMER_OWES_US\s+NUMBER\(18,2\) DEFAULT 0 NOT NULL/.test(text));
for(const name of [...text.matchAll(/CONSTRAINT (\w+)|CREATE INDEX (\w+)/g)].map(m=>m[1]||m[2]))assert(name.length<=30,name);
const rawNames=[...text.matchAll(/CONSTRAINT (\w+)/g)].map(m=>m[1]);assert.equal(new Set(rawNames).size,rawNames.length);
for(const [,url]of text.matchAll(/\]\(([^)]+)\)/g))if(!/^https?:/.test(url))assert(fs.existsSync(path.resolve('docs',url)),url);
const hashes=JSON.parse(fs.readFileSync('tmp/db-review-2026-11-20/runtime-hashes.json','utf8'));
for(const [p,hash]of Object.entries(hashes))assert.equal(crypto.createHash('sha256').update(fs.readFileSync(p)).digest('hex'),hash,'Runtime/schema contract changed '+p);
console.log(JSON.stringify({tables:5,compositePrimaryKeys:5,foreignKeys,indexedForeignKeys:foreignKeys,explicitIndexes,flag:'CHAR(1)',storedBalance:'NUMBER(18,2) DEFAULT 0 NOT NULL',runtimeAndMigrationFiles:'unchanged'}));
